#!/usr/bin/env python3
"""Turn a folder of photos into photos.h for the sketch.

Each photo is centre-cropped to a square (or use --focus to move the crop window),
resized to 240x240 and saved as a baseline (non-progressive) JPEG, then written into a C
array in flash. Baseline JPEGs need less RAM to decode on the ESP32.

    pip install pillow            (pillow-heif too, if you have iPhone .heic files)
    python make_photos_h.py my_photos/ ../photo_gallery/photos.h

Flash budget: the sketch itself is about 2 MB, so with a 3 MB app partition a few hundred
KB to ~1 MB of photos is comfortable. At the default quality 80 a photo is 10-25 KB; the
script prints the total so you can judge.

--focus 0..1 picks where the crop window sits along the long side of each photo
(0 = left/top, 0.5 = centre, 1 = right/bottom). Use a lower value to keep faces that sit
near the top of portrait photos, for example --focus 0.25.
"""
import argparse
import io
import pathlib
import sys

from PIL import Image, ImageOps

SIZE = 240
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".bmp", ".heic"}


def prepare(path, quality, focus):
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    w, h = img.size
    side = min(w, h)
    left = round((w - side) * (focus if w > h else 0.5))
    top = round((h - side) * (focus if h > w else 0.5))
    img = img.crop((left, top, left + side, top + side)).resize((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO()
    # subsampling=2 is 4:2:0, progressive=False is baseline
    img.save(buf, "JPEG", quality=quality, subsampling=2, progressive=False, optimize=False)
    return buf.getvalue()


def c_array(name, data):
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder", type=pathlib.Path, help="folder with your photos")
    ap.add_argument("output", type=pathlib.Path, help="photos.h to write")
    ap.add_argument("--quality", type=int, default=80, help="JPEG quality, default 80")
    ap.add_argument("--focus", type=float, default=0.5, help="crop position 0..1, default 0.5 (centre)")
    args = ap.parse_args()

    if any(p.suffix.lower() == ".heic" for p in args.folder.iterdir()):
        try:
            import pillow_heif
            pillow_heif.register_heif_opener()
        except ImportError:
            sys.exit("HEIC files found: pip install pillow-heif, or convert them to JPEG first.")

    files = sorted(p for p in args.folder.iterdir() if p.suffix.lower() in EXTS)
    if not files:
        sys.exit(f"No images found in {args.folder}")

    out = ["// Auto-generated by tools/make_photos_h.py: 240x240 baseline JPEGs stored in flash",
           "#pragma once", "#include <Arduino.h>", ""]
    total = 0
    for i, f in enumerate(files):
        data = prepare(f, args.quality, args.focus)
        total += len(data)
        print(f"photo_{i}: {f.name} -> {len(data) / 1024:.1f} KB")
        out.append(c_array(f"photo_{i}", data))
        out.append("")
    out.append("struct Photo { const uint8_t* data; unsigned int len; };")
    out.append("const Photo PHOTOS[] = {")
    out += [f"  {{photo_{i}, sizeof(photo_{i})}}," for i in range(len(files))]
    out.append("};")
    out.append("const int NUM_PHOTOS = sizeof(PHOTOS) / sizeof(PHOTOS[0]);")
    args.output.write_text("\n".join(out) + "\n")
    print(f"\n{len(files)} photos, {total / 1024:.0f} KB of JPEG data -> {args.output}")


if __name__ == "__main__":
    main()
